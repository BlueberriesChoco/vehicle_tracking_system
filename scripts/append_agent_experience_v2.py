def _pPr(element):
    return element.find(qn("w:pPr"))


def _rPr(element):
    return element.find(qn("w:rPr"))


def add_like(document, ref_para, text):
    """新增段落，复制参考段落的段落格式与字符格式。"""
    paragraph = document.add_paragraph()
    ref_ppr = _pPr(ref_para._p)
    if ref_ppr is not None:
        paragraph._p.insert(0, deepcopy(ref_ppr))
    run = paragraph.add_run(text)
    ref_runs = [r for r in ref_para.runs if _rPr(r._r) is not None]
    if ref_runs:
        run._r.insert(0, deepcopy(_rPr(ref_runs[0]._r)))
    return paragraph


def main():
    parser = argparse.ArgumentParser(description="Append sections 3-9 to the experience doc")
    parser.add_argument("--source", default=SOURCE)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    document = Document(args.source)
    body = document.element.body

    # 原稿末尾留了一个空的「标题 2」占位段，先清掉，避免留下空标题
    for p in list(document.paragraphs):
        if not p.text.strip() and p.style is not None and p.style.name == "Heading 2":
            body.remove(p._p)

    heading_ref = next(p for p in document.paragraphs if p.text.strip().startswith("二、"))
    body_ref = max(document.paragraphs, key=lambda p: len(p.text))

    for kind, text in CONTENT:
        add_like(document, heading_ref if kind == "h" else body_ref, text)

    document.save(args.output)
    print("saved", args.output)


if __name__ == "__main__":
    main()
