def set_cjk(style_or_run, name=BODY_FONT):
    """中文字体必须显式设置 eastAsia，否则只设 name 不生效。"""
    style_or_run.font.name = name
    element = style_or_run.element
    rpr = element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    rfonts.set(qn("w:eastAsia"), name)


def style_document(document):
    normal = document.styles["Normal"]
    set_cjk(normal)
    normal.font.size = Pt(10.5)
    normal.paragraph_format.line_spacing = 1.5
    normal.paragraph_format.space_after = Pt(6)

    for level, size in ((1, 15), (2, 12.5), (3, 11)):
        style = document.styles[f"Heading {level}"]
        set_cjk(style)
        style.font.size = Pt(size)
        style.font.bold = True
        style.font.color.rgb = RGBColor(0x1F, 0x3A, 0x5F)
        style.paragraph_format.space_before = Pt(12)
        style.paragraph_format.space_after = Pt(5)


def para(document, text, indent=0):
    p = document.add_paragraph()
    if indent:
        p.paragraph_format.left_indent = Cm(0.6 * indent)
    # 支持行内 **加粗**（python-docx 不解析 Markdown，必须自己拆 run）
    if "**" in text:
        for index, chunk in enumerate(text.split("**")):
            if not chunk:
                continue
            run = p.add_run(chunk)
            run.bold = (index % 2 == 1)
            set_cjk(run)
        return p
    run = p.add_run(text)
    set_cjk(run)
    return p


def bullet(document, text, bold_prefix=None):
    p = document.add_paragraph(style="List Bullet")
    if bold_prefix:
        run = p.add_run(bold_prefix)
        run.bold = True
        set_cjk(run)
    run = p.add_run(text)
    set_cjk(run)
    return p


def quote_block(document, text):
    p = document.add_paragraph()
    p.paragraph_format.left_indent = Cm(1.0)
    p.paragraph_format.right_indent = Cm(1.0)
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(10)
    shading = OxmlElement("w:shd")
    shading.set(qn("w:fill"), "F4F7FB")
    p._p.get_or_add_pPr().append(shading)
    run = p.add_run(text)
    run.italic = True
    set_cjk(run)
    return p


def shot(document, caption):
    """截图占位：留白给作者贴图，视觉上明显但不喧宾夺主。"""
    box = document.add_paragraph()
    box.alignment = WD_ALIGN_PARAGRAPH.CENTER
    box.paragraph_format.space_before = Pt(8)
    box.paragraph_format.space_after = Pt(0)
    shading = OxmlElement("w:shd")
    shading.set(qn("w:fill"), "F2F2F2")
    box._p.get_or_add_pPr().append(shading)
    run = box.add_run("［ 此处插入截图 ］")
    run.bold = True
    run.font.size = Pt(10.5)
    run.font.color.rgb = RGBColor(0x8A, 0x8A, 0x8A)
    set_cjk(run)

    note = document.add_paragraph()
    note.alignment = WD_ALIGN_PARAGRAPH.CENTER
    note.paragraph_format.space_before = Pt(0)
    note.paragraph_format.space_after = Pt(12)
    run = note.add_run(caption)
    run.italic = True
    run.font.size = Pt(9)
    run.font.color.rgb = RGBColor(0x8A, 0x8A, 0x8A)
    set_cjk(run)


def table(document, header, rows, widths=None):
    t = document.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    layout = OxmlElement("w:tblLayout")
    layout.set(qn("w:type"), "fixed")
    t._tbl.tblPr.append(layout)
    # 表头跨页重复，且禁止单行被拆到两页（否则会在页首留下半截行）
    tr_pr = t.rows[0]._tr.get_or_add_trPr()
    tr_pr.append(OxmlElement("w:tblHeader"))
    for row in t.rows:
        row._tr.get_or_add_trPr().append(OxmlElement("w:cantSplit"))

    hdr = t.rows[0].cells
    for i, text in enumerate(header):
        hdr[i].text = ""
        run = hdr[i].paragraphs[0].add_run(text)
        run.bold = True
        run.font.size = Pt(9.5)
        set_cjk(run)
    for row in rows:
        cells = t.add_row().cells
        for i, text in enumerate(row):
            cells[i].text = ""
            run = cells[i].paragraphs[0].add_run(text)
            run.font.size = Pt(9.5)
            set_cjk(run)
    if widths:
        for i, width in enumerate(widths):
            t.columns[i].width = Cm(width)
        for row in t.rows:
            for i, width in enumerate(widths):
                row.cells[i].width = Cm(width)
    document.add_paragraph()
    return t


