    doc.add_heading("十二、数据不够的时候怎么办", level=1)
    para(doc, "这是科研里最常态的问题：方法想好了，数据没有。这个项目 23 项指标里，"
              "17 项卡在这上面。")
    para(doc, "能走的路大致四条。**第一是等数据**——最踏实，但不可控：现场标定要有人去车道上量，"
              "违规标注要等查获案例慢慢攒，双机位要重新架。**第二是弱监督**——拿规则命中的结果"
              "当弱标签去训练再评估。这条路有循环论证的风险，等于用 A 验证 A，"
              "可以做，但结论只能内部参考。**第三是合成**——人为造一批异常样本来测。"
              "问题是造出来的异常和真实异常常常不是一回事，这个项目就吃过亏。"
              "**第四是换指标**——算不出召回率，就先算能算的：误报率、延迟、吞吐、"
              "证据可追溯率，这些不需要标注。")
    para(doc, "我最后的选择是：合成数据只用来验证「已知异常类型的检出率」（这个它确实能说明问题），"
              "坚决不用它冒充「未知异常的区分能力」；算不出来的指标一律留空，并写明缺什么，"
              "而不是拿一个看起来像样的数字顶上。")
    para(doc, "这件事听起来像「没做完」，其实是可信度的一部分。一份写着「6 项达标、10 项等数据、"
              "2 项未达标、5 项没有真值」的报告，比一份「全部通过」的报告更让人敢用——"
              "因为前者告诉你边界在哪，后者要你自己去试。")
    para(doc, "举个很小的例子。有个指标一直是 0，我第一版归因是「缺车牌识别」。"
              "后来发现还缺第二个条件：这段录像只有 66 分钟，每辆车只经过一次，"
              "就算车牌完美，「一天之内的高频通行」也无从观察。两个条件缺一不可。"
              "如果当时按第一版结论写「补上车牌就好了」，对方补了车牌指标还是 0，"
              "那才是真的伤信任。")
    para(doc, "所以对「为什么是 0」这类问题，我现在的标准动作是：把所有必要条件列全，"
              "再逐个对照现状。列不全就先不写结论。")
