def _pPr_of(paragraph):
    return paragraph._p.find(qn("w:pPr"))


def _rPr_of(paragraph):
    for run in paragraph.runs:
        rpr = run._r.find(qn("w:rPr"))
        if rpr is not None:
            return rpr
    return None


def add_like(document, ref_para, text, italic=False, grey=False, center=False):
    """新增段落，并复制参考段落的段落格式与字符格式。"""
    paragraph = document.add_paragraph()

    ppr = _pPr_of(ref_para)
    if ppr is not None:
        paragraph._p.insert(0, deepcopy(ppr))

    if center:
        from docx.enum.text import WD_ALIGN_PARAGRAPH
        paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER

    run = paragraph.add_run(text)
    rpr = _rPr_of(ref_para)
    if rpr is not None:
        copied = deepcopy(rpr)
        run._r.insert(0, copied)
        # 补齐参考段落里可能缺失、但会影响中英混排的属性：
        # hint=eastAsia 让数字/字母跟随中文字体，lang 缺 val 时 Word 会按系统语言猜
        rfonts = copied.find(qn("w:rFonts"))
        if rfonts is not None and rfonts.get(qn("w:hint")) is None:
            rfonts.set(qn("w:hint"), "eastAsia")
        lang = copied.find(qn("w:lang"))
        if lang is not None:
            if not lang.get(qn("w:val")):
                lang.set(qn("w:val"), "en-US")
            if not lang.get(qn("w:eastAsia")):
                lang.set(qn("w:eastAsia"), "zh-CN")
    if italic:
        run.italic = True
    if grey:
        run.font.color.rgb = RGBColor(0x80, 0x80, 0x80)
    return paragraph


def main():
    parser = argparse.ArgumentParser(description="Append research/algorithm sections to the experience doc")
    parser.add_argument("--source", default=SOURCE)
    parser.add_argument("--output", default=None)
    args = parser.parse_args()

    document = Document(args.source)
    paragraphs = document.paragraphs

    # 参考段落：标题取一个现有小节标题，正文取第一段正文，截图位沿用图注字号
    heading_ref = next(p for p in paragraphs if p.text.strip().startswith("二、"))
    body_ref = next(p for p in paragraphs if len(p.text.strip()) > 80)
    caption_ref = next((p for p in paragraphs if p.text.strip().startswith("图为")), body_ref)

    for kind, text in CONTENT:
        if kind == "h":
            add_like(document, heading_ref, text)
        elif kind == "shot":
            add_like(document, caption_ref, f"【{text}】", italic=True, grey=True, center=True)
        else:
            add_like(document, body_ref, text)

    target = args.output or args.source
    try:
        document.save(target)
        print("saved", target)
    except PermissionError:
        fallback = os.path.splitext(args.source)[0] + "-续写.docx"
        document.save(fallback)
        print("原文件被占用，已另存为：", fallback)


if __name__ == "__main__":
    main()
